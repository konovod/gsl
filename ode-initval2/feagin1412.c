static int
feagin1412_reset (void *vstate, size_t dim)
{
  feagin1412_state_t *state = (feagin1412_state_t *) vstate;

  int i;

  for (i = 0; i < 35; i++)
    {
      DBL_ZERO_MEMSET (state->k[i], dim);
    }

  DBL_ZERO_MEMSET (state->ytmp, dim);
  DBL_ZERO_MEMSET (state->y0, dim);

  return GSL_SUCCESS;
}

static unsigned int
feagin1412_order (void *vstate)
{
  feagin1412_state_t *state = (feagin1412_state_t *) vstate;
  state = 0;                    /* prevent warnings about unused parameters */
  return 14;
}

static void
feagin1412_free (void *vstate)
{
  feagin1412_state_t *state = (feagin1412_state_t *) vstate;
  int i;

  for (i = 0; i < 35; i++)
    {
      free (state->k[i]);
    }

  free (state->ytmp);
  free (state->y0);
  free (state);
}

